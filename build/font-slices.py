#!/usr/bin/env python3
"""build/font-slices.py — cut the two big fallback fonts into slices.

    npm run fonts        (runs this after build/fonts.py; needs fonttools + brotli)

EB Garamond (290 KB) and Fairfax HD (750 KB) are fallbacks: a page needs a
handful of their glyphs — some Cyrillic, the Graflect block — or none at all.
Declared as one file each, the browser has to download the whole font to draw
one character, and has to download it merely to find out it CAN'T draw one.

So each font is declared as several @font-face rules of the same family, each
a slice with an exact `unicode-range`. The browser picks, per page, only the
slices whose range covers a character actually on that page:

    Garamond   latin · latin-ext · greek · cyrillic · rest
    FairfaxHD  graflect (U+EC70–ECEF) · latin · rest

The slices (styles/fonts/slices/*.woff2) are committed; the @font-face rules
are written into styles/pelmeni2025.css between the FONT-SLICES markers.
"""
from pathlib import Path
import re
import sys

try:
    from fontTools.ttLib import TTFont
    from fontTools import subset
    import brotli  # noqa: F401
except ImportError:
    sys.exit("font-slices.py needs: pip install fonttools brotli")

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "styles" / "fonts"
OUT = FONTS / "slices"
CSS = ROOT / "styles" / "pelmeni2025.css"

R = lambda a, b=None: (a, a if b is None else b)
LATIN = [R(0x0000, 0x00FF), R(0x0131), R(0x0152, 0x0153), R(0x02BB, 0x02BC), R(0x02C6), R(0x02DA), R(0x02DC),
         R(0x2000, 0x206F), R(0x20AC), R(0x2122), R(0x2191), R(0x2193), R(0x2212), R(0x2215), R(0xFEFF), R(0xFFFD)]
LATIN_EXT = [R(0x0100, 0x036F), R(0x1E00, 0x1EFF), R(0x2C60, 0x2C7F), R(0xA720, 0xA7FF)]
GREEK = [R(0x0370, 0x03FF), R(0x1F00, 0x1FFF)]
CYRILLIC = [R(0x0400, 0x052F), R(0x1C80, 0x1C88), R(0x2DE0, 0x2DFF), R(0xA640, 0xA69F)]
GRAFLECT = [R(0xEC70, 0xECEF)]

# family, source, [(slice name, ranges or None for "everything left"), ...],
# gap to merge in the CSS range of "rest", layout features (None = fontTools' default set)
PLAN = [
    # Garamond keeps only the default OpenType features (kerning, ligatures,
    # marks): its small caps, swashes and the rest double each slice, and the
    # site never asks for them. Fairfax keeps everything (Graflect shaping).
    ("Garamond", "EBGaramond.ttf", [("latin", LATIN), ("latin-ext", LATIN_EXT), ("greek", GREEK), ("cyrillic", CYRILLIC), ("rest", None)], 0, None),
    ("FairfaxHD", "FairfaxHD.ttf", [("graflect", GRAFLECT), ("latin", LATIN + LATIN_EXT), ("rest", None)], 256, ["*"]),
]


def to_ranges(cps, gap=0, keep_out=()):
    """Sorted codepoints → [(start, end)], merging runs separated by <= gap.

    A merge never swallows a codepoint in `keep_out` (another slice's
    characters): two slices claiming the same character would make the browser
    fetch both, which is the whole thing this file exists to prevent.
    """
    import bisect
    fence = sorted(keep_out)
    out = []
    for cp in sorted(cps):
        if out and cp - out[-1][1] <= gap + 1:
            i = bisect.bisect_right(fence, out[-1][1])
            if i >= len(fence) or fence[i] > cp:
                out[-1][1] = cp
                continue
        out.append([cp, cp])
    return out


def css_range(ranges):
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    rules = []
    print("Writing font slices:")
    for family, src, slices, gap, features in PLAN:
        cmap = set(TTFont(FONTS / src).getBestCmap())
        left = set(cmap)
        for name, ranges in slices:
            want = set(left) if ranges is None else {cp for cp in left if any(a <= cp <= b for a, b in ranges)}
            left -= want
            if not want:
                continue
            opts = subset.Options()
            opts.flavor = "woff2"
            if features:
                opts.layout_features = features
            opts.name_IDs = ["*"]          # keep the copyright/licence records
            opts.notdef_outline = True
            font = TTFont(FONTS / src)
            sub = subset.Subsetter(options=opts)
            sub.populate(unicodes=sorted(want))
            sub.subset(font)
            font.flavor = "woff2"
            out = OUT / f"{Path(src).stem}-{name}.woff2"
            font.save(out)
            print(f"  {out.name:30} {out.stat().st_size / 1e3:7.1f} KB  ({len(want)} characters)")
            rules.append(
                f"@font-face {{\n  font-family: '{family}';\n  src: url('fonts/slices/{out.name}') format('woff2');\n"
                f"  font-display: swap;\n  unicode-range: {css_range(to_ranges(want, gap if ranges is None else 0, cmap - want))};\n}}")
    block = "/*FONT-SLICES:START (generated by build/font-slices.py — do not edit) */\n" + "\n".join(rules) + "\n/*FONT-SLICES:END*/"
    css = CSS.read_text(encoding="utf-8")
    if "/*FONT-SLICES:START" not in css:
        sys.exit("styles/pelmeni2025.css has no FONT-SLICES markers")
    CSS.write_text(re.sub(r"/\*FONT-SLICES:START[\s\S]*?/\*FONT-SLICES:END\*/", lambda _m: block, css), encoding="utf-8")
    print(f"  → {len(rules)} @font-face rules written to {CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
